// Fills {who}/{where}; falls back to nothing (the caller keeps the short line).
export function huntStory(kind, key, who, where) {
    const list = (kind === 'boss' ? BOSS_STORIES : RARE_STORIES)[key];
    if (!list || !list.length) return '';
    const t = list[Math.floor(Math.random() * list.length)].replace(/\{who\}/g, who).replace(/\{where\}/g, where);
    return t.charAt(0).toUpperCase() + t.slice(1);
}

